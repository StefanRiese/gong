// Generates lib/src/desktop/build_info.g.dart for release builds.
//
//   dart run tool/embed_assets.dart --version v1.2.3 \
//       [--web ../web] [--tray-icon ../deploy/desktop/tray-icon.png]
//
// --web embeds the web UI (desktop builds), --tray-icon the Windows tray icon.
// deploy/build-release.sh restores the committed placeholder afterwards.

import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  String? option(String name) {
    final i = args.indexOf(name);
    return i >= 0 && i + 1 < args.length ? args[i + 1] : null;
  }

  final version = option('--version');
  final webDir = option('--web');
  final trayIcon = option('--tray-icon');
  final out = option('--out') ?? 'lib/src/desktop/build_info.g.dart';
  if (version == null) {
    stderr.writeln(
      'usage: embed_assets.dart --version V [--web DIR] '
      '[--tray-icon PNG] [--out FILE]',
    );
    exit(64);
  }

  final files = <String, String>{};
  if (webDir != null) {
    final root = Directory(webDir).absolute;
    final entries = root.listSync(recursive: true).whereType<File>().toList()
      ..sort((a, b) => a.path.compareTo(b.path));
    for (final f in entries) {
      final rel = f.path
          .substring(root.path.length + 1)
          .replaceAll(Platform.pathSeparator, '/');
      if (rel == 'README.md' || rel.split('/').any((p) => p.startsWith('.'))) {
        continue;
      }
      files[rel] = base64.encode(f.readAsBytesSync());
    }
    if (!files.containsKey('index.html')) {
      stderr.writeln('$webDir has no index.html');
      exit(1);
    }
  }
  final icon = trayIcon == null
      ? ''
      : base64.encode(File(trayIcon).readAsBytesSync());

  final b = StringBuffer()
    ..writeln('// GENERATED by tool/embed_assets.dart – do not edit or commit.')
    ..writeln(
      '// ignore_for_file: unnecessary_nullable_for_final_variable_declarations',
    )
    ..writeln()
    ..writeln('const String? buildVersion = ${jsonEncode(version)};')
    ..writeln()
    ..writeln('const Map<String, String> embeddedWebFiles = {');
  for (final MapEntry(:key, :value) in files.entries) {
    b.writeln('  ${jsonEncode(key)}: ${jsonEncode(value)},');
  }
  b
    ..writeln('};')
    ..writeln()
    ..writeln('const String trayIconPng = ${jsonEncode(icon)};');
  // JSON strings are valid Dart string literals except for "$".
  File(out).writeAsStringSync(b.toString().replaceAll(r'$', r'\$'));
  stdout.writeln(
    'Wrote $out (${files.length} web files, '
    '${icon.isEmpty ? 'no' : 'with'} tray icon)',
  );
}
